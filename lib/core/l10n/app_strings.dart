  static String get(String key, AppLocale locale) {
    return localizedValues[locale.code]?[key] ?? localizedValues['id']?[key] ?? key;
  }

  /// Helper with param interpolation: replaces {key} with value
  static String tr(String key, AppLocale locale, [Map<String, String>? params]) {
    var v = get(key, locale);
    if (params != null) {
      params.forEach((k, val) {
        v = v.replaceAll('{$k}', val);
      });
    }
    return v;
  }

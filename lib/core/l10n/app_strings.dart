library;

enum AppLocale { id, en }

extension AppLocaleExt on AppLocale {
  String get code => name;
  String get displayName {
    switch (this) {
      case AppLocale.id:
        return 'Indonesia';
      case AppLocale.en:
        return 'English';
    }
  }

  String get nativeName {
    switch (this) {
      case AppLocale.id:
        return 'Bahasa Indonesia';
      case AppLocale.en:
        return 'English';
    }
  }

  static AppLocale fromCode(String? code) {
    if (code == 'en') return AppLocale.en;
    return AppLocale.id;
  }
}

